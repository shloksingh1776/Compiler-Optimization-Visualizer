/**
 * LEXICAL ANALYSIS  (Phase 1 of the compiler)
 * ===========================================
 *
 * COMPILER CONCEPT: the lexical analyser -- also called the scanner or lexer --
 * reads the source program one character at a time and groups the characters
 * into *tokens*. It also discards things the parser does not care about:
 * whitespace and comments.
 *
 *      characters  -->  [ LEXER ]  -->  tokens  -->  [ PARSER ]
 *
 * WHY IS THIS A SEPARATE PHASE?
 *   1. It simplifies the parser enormously: the grammar can be written over
 *      tokens instead of characters.
 *   2. Whitespace and comment handling lives in exactly one place.
 *   3. It is where source positions are captured, which every later phase
 *      needs for error messages.
 *
 * IMPLEMENTATION APPROACH
 * This is a hand-written scanner with one character of lookahead, rather than
 * a table generated by a tool such as Lex/Flex. For a language this small a
 * hand-written scanner is shorter, produces better error messages, and -- most
 * importantly for this project -- every decision it makes is visible in the
 * code and can be explained.
 *
 * Formally the scanner recognises these regular expressions:
 *
 *      digit       ->  [0-9]
 *      letter      ->  [A-Za-z_]
 *      NUMBER      ->  digit+
 *      IDENTIFIER  ->  letter (letter | digit)*
 *      comment     ->  "//" [^\n]*
 *      whitespace  ->  [ \t\r\n]+
 *
 * DETERMINISM: the scanner has no randomness and no dependence on anything
 * outside its input string, so tokenize(s) always returns exactly the same
 * result for the same s.
 */

import { KEYWORDS, TokenType, type Token } from './tokens.ts';
import { lexicalError, type CompilerError, type SourceSpan } from '../errors.ts';

/** Result of scanning a source program. */
export interface LexResult {
  /** The token stream. Always ends with exactly one EOF token. */
  readonly tokens: Token[];
  /** All lexical errors found. Empty means the scan succeeded. */
  readonly errors: CompilerError[];
}

/** Largest / smallest value representable in a 32-bit signed integer. */
const INT_MAX = 2147483647;

/* ------------------------------------------------------------------ */
/* Character classification helpers                                    */
/* ------------------------------------------------------------------ */

function isDigit(ch: string): boolean {
  return ch >= '0' && ch <= '9';
}

/**
 * A letter for the purposes of an identifier. Underscore counts as a letter,
 * which is the usual C convention (`_temp` is a legal name).
 */
function isLetter(ch: string): boolean {
  return (ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || ch === '_';
}

function isIdentifierPart(ch: string): boolean {
  return isLetter(ch) || isDigit(ch);
}

/* ------------------------------------------------------------------ */
/* The scanner                                                         */
/* ------------------------------------------------------------------ */

/**
 * The scanner is a small class purely to keep the cursor state (`pos`, `line`,
 * `column`) together. It is created, used once and thrown away by `tokenize`,
 * so no state ever leaks between two compilations.
 */
class Lexer {
  private readonly source: string;
  private readonly tokens: Token[] = [];
  private readonly errors: CompilerError[] = [];

  /** 0-based absolute offset of the next character to read. */
  private pos = 0;
  /** 1-based line number of the next character. */
  private line = 1;
  /** 1-based column number of the next character. */
  private column = 1;

  constructor(source: string) {
    this.source = source;
  }

  /* ---------------- cursor primitives ---------------- */

  private isAtEnd(): boolean {
    return this.pos >= this.source.length;
  }

  /** The next character without consuming it, or '' at end of input. */
  private peek(): string {
    return this.source[this.pos] ?? '';
  }

  /** The character after next without consuming it, or '' at end of input. */
  private peekNext(): string {
    return this.source[this.pos + 1] ?? '';
  }

  /**
   * Consume and return one character, keeping line and column in step.
   * Newlines are the only characters that change the line number.
   */
  private advance(): string {
    const ch = this.source[this.pos] ?? '';
    this.pos++;
    if (ch === '\n') {
      this.line++;
      this.column = 1;
    } else {
      this.column++;
    }
    return ch;
  }

  /* ---------------- token construction ---------------- */

  private addToken(
    type: TokenType,
    start: number,
    startLine: number,
    startColumn: number,
    value?: number
  ): void {
    const lexeme = this.source.slice(start, this.pos);
    // Only attach `value` for NUMBER tokens, so the UI column stays empty
    // for everything else.
    const token: Token =
      value === undefined
        ? { type, lexeme, line: startLine, column: startColumn, start, end: this.pos }
        : { type, lexeme, value, line: startLine, column: startColumn, start, end: this.pos };
    this.tokens.push(token);
  }

  private addError(message: string, span: SourceSpan): void {
    this.errors.push(lexicalError(message, span));
  }

  /* ---------------- main loop ---------------- */

  scan(): LexResult {
    while (true) {
      this.skipWhitespaceAndComments();
      if (this.isAtEnd()) break;
      this.scanToken();
    }

    // COMPILER CONCEPT: append an explicit end-of-file marker so the parser
    // can match "end of input" like any other terminal symbol.
    this.tokens.push({
      type: TokenType.EOF,
      lexeme: '',
      line: this.line,
      column: this.column,
      start: this.pos,
      end: this.pos,
    });

    return { tokens: this.tokens, errors: this.errors };
  }

  /**
   * Skip everything the parser does not need to see.
   *
   * Note that the cursor still advances through whitespace and comments, so
   * line and column numbers stay correct for the tokens that follow. Getting
   * this wrong is why some compilers report errors on the wrong line.
   */
  private skipWhitespaceAndComments(): void {
    while (!this.isAtEnd()) {
      const ch = this.peek();

      if (ch === ' ' || ch === '\t' || ch === '\r' || ch === '\n') {
        this.advance();
        continue;
      }

      // Single line comment: "//" runs to the end of the line.
      // The newline itself is left in place so the whitespace branch above
      // consumes it and bumps the line counter.
      if (ch === '/' && this.peekNext() === '/') {
        while (!this.isAtEnd() && this.peek() !== '\n') {
          this.advance();
        }
        continue;
      }

      // Anything else is the start of a real token.
      return;
    }
  }

  /** Scan exactly one token, assuming we are not at end of input. */
  private scanToken(): void {
    const start = this.pos;
    const startLine = this.line;
    const startColumn = this.column;
    const ch = this.peek();

    // --- numbers ---
    if (isDigit(ch)) {
      this.scanNumber(start, startLine, startColumn);
      return;
    }

    // --- identifiers and keywords ---
    if (isLetter(ch)) {
      this.scanIdentifier(start, startLine, startColumn);
      return;
    }

    // --- two-character comparison/equality/logical tokens ---
    if ((ch === '<' || ch === '>' || ch === '=' || ch === '!' || ch === '&' || ch === '|') && this.peekNext() === (ch === '&' ? '&' : ch === '|' ? '|' : '=')) {
      this.advance();
      this.advance();
      const type =
        ch === '<' ? TokenType.LE :
        ch === '>' ? TokenType.GE :
        ch === '=' ? TokenType.EQ :
        ch === '!' ? TokenType.NE :
        ch === '&' ? TokenType.AND_AND : TokenType.OR_OR;
      this.addToken(type, start, startLine, startColumn);
      return;
    }

    // --- compound assignment before single-character operators ---
    if (['+', '-', '*', '/', '%'].includes(ch) && this.peekNext() === '=') {
      this.advance();
      this.advance();
      const types: Record<string, TokenType> = {
        '+': TokenType.PLUS_ASSIGN, '-': TokenType.MINUS_ASSIGN,
        '*': TokenType.STAR_ASSIGN, '/': TokenType.SLASH_ASSIGN,
        '%': TokenType.PERCENT_ASSIGN,
      };
      this.addToken(types[ch]!, start, startLine, startColumn);
      return;
    }

    // --- increment/decrement before single-character + / - ---
    // Maximal munch: `++` and `--` are one token when the two characters are
    // adjacent. A separated `+ +` or `- -` remains two ordinary operators.
    if ((ch === '+' || ch === '-') && this.peekNext() === ch) {
      this.advance();
      this.advance();
      this.addToken(ch === '+' ? TokenType.INCREMENT : TokenType.DECREMENT, start, startLine, startColumn);
      return;
    }

    // --- single character tokens ---
    this.advance();
    switch (ch) {
      case '+':
        this.addToken(TokenType.PLUS, start, startLine, startColumn);
        return;
      case '-':
        // NOTE: the scanner does NOT try to decide whether this is binary
        // subtraction or unary negation. That is a *grammatical* question and
        // therefore the parser's job. The scanner only reports "a minus sign".
        this.addToken(TokenType.MINUS, start, startLine, startColumn);
        return;
      case '*':
        this.addToken(TokenType.STAR, start, startLine, startColumn);
        return;
      case '%':
        this.addToken(TokenType.PERCENT, start, startLine, startColumn);
        return;
      case '/':
        // A "//" pair was already consumed as a comment above, so a slash
        // reaching this point is genuine division.
        this.addToken(TokenType.SLASH, start, startLine, startColumn);
        return;
      case '=':
        this.addToken(TokenType.ASSIGN, start, startLine, startColumn);
        return;
      case '<':
        this.addToken(TokenType.LT, start, startLine, startColumn);
        return;
      case '>':
        this.addToken(TokenType.GT, start, startLine, startColumn);
        return;
      case '!':
        this.addToken(TokenType.BANG, start, startLine, startColumn);
        return;
      case '&':
        this.addError("Unexpected character '&' (did you mean '&&')", {
          line: startLine, column: startColumn, start, end: this.pos
        });
        return;
      case '|':
        this.addError("Unexpected character '|' (did you mean '||')", {
          line: startLine, column: startColumn, start, end: this.pos
        });
        return;
      case '(':
        this.addToken(TokenType.LPAREN, start, startLine, startColumn);
        return;
      case ')':
        this.addToken(TokenType.RPAREN, start, startLine, startColumn);
        return;
      case ';':
        this.addToken(TokenType.SEMICOLON, start, startLine, startColumn);
        return;
      case '{':
        this.addToken(TokenType.LBRACE, start, startLine, startColumn);
        return;
      case '}':
        this.addToken(TokenType.RBRACE, start, startLine, startColumn);
        return;
      case ',':
        this.addToken(TokenType.COMMA, start, startLine, startColumn);
        return;
      case '?':
        this.addToken(TokenType.QUESTION, start, startLine, startColumn);
        return;
      case ':':
        this.addToken(TokenType.COLON, start, startLine, startColumn);
        return;
      default:
        // ERROR RECOVERY: report the bad character, then carry on scanning
        // from the next one. This lets us collect every lexical error in the
        // file in a single pass instead of stopping at the first.
        this.addError(`Unexpected character '${ch}'`, {
          line: startLine,
          column: startColumn,
          start,
          end: this.pos,
        });
        return;
    }
  }

  /**
   * NUMBER -> digit+
   *
   * Two error cases are detected here:
   *   1. A digit run immediately followed by a letter, e.g. `12abc`. Left
   *      alone, the scanner would happily produce NUMBER(12) then
   *      IDENTIFIER(abc), and the parser would report a confusing syntax
   *      error. Catching it in the scanner gives a much clearer message.
   *   2. A literal too large for a 32-bit signed integer. MiniC arithmetic is
   *      32-bit, so accepting the literal would make constant folding
   *      silently disagree with the source.
   */
  /**
   * NUMBER -> digit+ | digit+ '.' digit+
   *
   * Integer literals retain the existing 32-bit check. Decimal literals are
   * represented as JavaScript numbers and are intentionally limited to the
   * simple `digits.digits` form for this small compiler.
   */
  private scanNumber(start: number, startLine: number, startColumn: number): void {
    while (!this.isAtEnd() && isDigit(this.peek())) this.advance();

    let isFloat = false;
    if (this.peek() === '.') {
      isFloat = true;
      this.advance();
      if (!isDigit(this.peek())) {
        while (!this.isAtEnd() && (isLetter(this.peek()) || isDigit(this.peek()) || this.peek() === '.')) {
          this.advance();
        }
        const badLexeme = this.source.slice(start, this.pos);
        this.addError(`Malformed floating-point number '${badLexeme}': expected digits after '.'`, {
          line: startLine, column: startColumn, start, end: this.pos
        });
        return;
      }
      while (!this.isAtEnd() && isDigit(this.peek())) this.advance();
    }

    // Reject things such as 12abc and 12.5abc rather than producing
    // misleading token streams.
    if (!this.isAtEnd() && (isLetter(this.peek()) || this.peek() === '.')) {
      while (!this.isAtEnd() && (isIdentifierPart(this.peek()) || this.peek() === '.')) this.advance();
      const badLexeme = this.source.slice(start, this.pos);
      this.addError(`Malformed number '${badLexeme}'`, {
        line: startLine, column: startColumn, start, end: this.pos
      });
      return;
    }

    const text = this.source.slice(start, this.pos);
    const value = Number(text);
    if (!Number.isFinite(value)) {
      this.addError(`Numeric literal '${text}' is outside the supported range`, {
        line: startLine, column: startColumn, start, end: this.pos
      });
      return;
    }

    if (!isFloat && value > INT_MAX) {
      this.addError(
        `Integer literal '${text}' is too large for a 32-bit int (maximum ${INT_MAX})`,
        { line: startLine, column: startColumn, start, end: this.pos }
      );
      return;
    }

    this.addToken(TokenType.NUMBER, start, startLine, startColumn, value);
  }

  /**
   * IDENTIFIER -> letter (letter | digit)*
   *
   * MAXIMAL MUNCH: consume the longest possible run of identifier characters
   * first, and only then check the keyword table. This is what makes
   * `integer` a single identifier rather than the keyword `int` followed by
   * `eger`.
   */
  private scanIdentifier(start: number, startLine: number, startColumn: number): void {
    while (!this.isAtEnd() && isIdentifierPart(this.peek())) {
      this.advance();
    }
    const lexeme = this.source.slice(start, this.pos);
    const keywordType = KEYWORDS[lexeme];
    this.addToken(keywordType ?? TokenType.IDENTIFIER, start, startLine, startColumn);
  }
}

/* ------------------------------------------------------------------ */
/* Public API                                                          */
/* ------------------------------------------------------------------ */

/**
 * Run lexical analysis on a MiniC source program.
 *
 * Pure function: no shared state, no side effects, fully deterministic.
 *
 * @example
 *   tokenize("int a = 10;")
 *   // tokens: INT, IDENTIFIER(a), ASSIGN, NUMBER(10), SEMICOLON, EOF
 */
export function tokenize(source: string): LexResult {
  return new Lexer(source).scan();
}
